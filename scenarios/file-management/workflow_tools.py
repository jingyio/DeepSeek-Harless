"""Explicit first-batch workflow surface; original ReportScene and certificates stay unchanged."""
from __future__ import annotations
import json,os
from pathlib import Path
from typing import Literal
from mcp.server import MCPServer
from mcp.server.mcpserver.exceptions import ToolError
from mcp.types import ToolAnnotations
from common import HERE,digest,sha,save
from file_tools import Action
from report_tools import ReportScene,report_version
from workflow_contract import VERSION,contract
from workflow_delivery import current_ids,finish_report,report_facts

TOOLS=('read_task','list_files','select_files','pin_file','read_file','collect_reads','hash_files','build_index',
       'search_index','compare_snapshot','preview_actions','execute_plan','restore_plan','submit_report')
def workflow_version():
    return digest({'workflow_tools.py':sha(__file__),'workflow_contract.py':sha(HERE/'workflow_contract.py'),
                   'workflow_delivery.py':sha(HERE/'workflow_delivery.py'),'report_version':report_version(),'contract':VERSION})

class WorkflowScene(ReportScene):
    def __init__(self,spec,output):
        super().__init__(spec,output);self.workflow=contract(spec)
        if self.workflow.workflow_id=='FM38':raise ValueError('recovery uses the explicit recovery_tools entry')
        if self.report_contract['kind']!='task_result':raise ValueError('workflow requires task_result')
        self.execution_version=workflow_version()
    def read_task(self):
        facts={**super().read_task(),'workflow_contract':self.workflow.model_dump(),
                'workflow_execution_version_sha256':workflow_version(),
                'report_file_ids_meaning':'all current files, generated by MCP; pass [] as the legacy hint',
                'task_result_serialization':report_facts()}
        if self.workflow.workflow_id=='FM05':
            facts['workflow_effect_constraints']={
                'merge_output_identity':'exactly one output per original source SHA group at submission, including empty files; at most one across all destination_prefixes and all executed plans',
                'representative_choice':'read the actual merge rule; the effect guard does not choose a representative',
                'replace_existing_output':'use authorized restore_plan in reverse execution order before replacing a representative',
                'rejected_preview_has_effects':False}
        return facts
    def pin_file(self,file_id:str):
        _,name=self.file(file_id)
        if name not in self.workflow.allowed_reads:raise ToolError('read outside workflow original scope')
        return super().pin_file(file_id)
    def select_files(self,file_ids:list[str]):
        if self.workflow.workflow_id=='FM13':
            paths={self.file(fid)[1] for fid in file_ids}
            if paths & set(self.workflow.source_paths) and not set(self.workflow.context_paths)<={r['path'] for r in self.reads.values()}:
                raise ToolError('read actual release notice before selecting versions')
        return super().select_files(file_ids)
    def preview_actions(self,actions:list[Action]):
        self.active();c=self.workflow
        if not set(c.required_reads)<={r['path'] for r in self.reads.values()}:raise ToolError('read all required originals before effects')
        allowed={'FM01':'move','FM05':'copy','FM13':'copy','FM17':'copy','FM21':'archive'}[c.workflow_id]
        for raw in actions:
            a=raw.model_dump() if isinstance(raw,Action) else Action(**raw).model_dump()
            if a['op']!=allowed or a['format']!='none' or not any(a['destination'].startswith(p) for p in c.destination_prefixes):raise ToolError('effect outside workflow grant')
            for fid in a['file_ids']:
                _,name=self.file(fid)
                original=name in c.source_paths
                backup=c.workflow_id=='FM17' and name.startswith('backup-set/') and a['destination'].startswith('recovery-drill/')
                if not original and not backup:raise ToolError('source outside workflow grant')
                if c.workflow_id=='FM21' and not name.startswith('materials/package/'):
                    raise ToolError('excluded/pending candidate cannot enter the delivery archive')
                if c.workflow_id=='FM01':
                    row=next((r for r in self.reads.values() if r['path']==name),None)
                    if not row or row['status']!='readable' or not row['text'].strip():raise ToolError('unreadable/metadata/empty material must remain pending')
                if c.workflow_id=='FM17':
                    target=('recovery-drill/'+name[len('backup-set/'):] if backup else 'backup-set/'+name[len('source/'):])
                    origin='source/'+name[len('backup-set/'):] if backup else name
                    if origin not in c.source_paths or self.expected[name]!=self.spec['initial_snapshot'][origin] or a['destination']!=target:
                        raise ToolError('backup source/target/byte mapping differs')
        self._merge_copy_guard(actions)
        return super().preview_actions(actions)
    def _merge_copy_guard(self,actions):
        """Check actual byte classes across plans; never inspect the private oracle or choose paths."""
        c=self.workflow
        if c.workflow_id!='FM05':return
        occupied={}
        for name,h in self.expected.items():
            if any(name.startswith(p) for p in c.destination_prefixes):
                if h in occupied:raise ToolError('duplicate SHA group already exists in merge outputs; restore authorized plans before replacing')
                occupied[h]=name
        for raw in actions:
            a=raw.model_dump() if isinstance(raw,Action) else Action(**raw).model_dump()
            if a['op']!='copy' or a['format']!='none' or len(a['file_ids'])!=1:
                raise ToolError('merge requires one byte-preserving input per copy')
            _,name=self.file(a['file_ids'][0])
            if name not in c.source_paths or not any(a['destination'].startswith(p) for p in c.destination_prefixes):
                raise ToolError('merge effect outside original source/destination grant')
            h=self.expected[name]
            if h in occupied:
                raise ToolError('duplicate SHA group '+h+' already assigned to '+occupied[h]
                                +'; output this byte group once. Read the actual representative rule; restore authorized plans before replacing an existing output.')
            occupied[h]=a['destination']
    def execute_plan(self,plan_id:str):
        """Recheck merge byte uniqueness before effects; preserve idempotent receipts and stale guards."""
        self.active()
        if plan_id not in self.receipts:
            plan=self.plans.get(plan_id)
            if not plan or plan['snapshot']!=self.expected:raise ToolError('unknown or stale plan')
            self._merge_copy_guard(plan['actions'])
        return super().execute_plan(plan_id)
    def submit_report(self,summary:str,file_ids:list[str],gaps:list[str],report_kind:Literal['task_result','inspection','literal_search'],search_receipt_id:str|None=None):
        """Submit summary (1-2000 characters) and gaps. Use task_result, file_ids=[], omit search receipt; MCP derives all current identities and actual receipts. Independent acceptance checks effects."""
        self.active()
        if self.workflow.workflow_id=='FM05':
            self._merge_copy_guard([])
            produced={h for n,h in self.expected.items() if any(n.startswith(p) for p in self.workflow.destination_prefixes)}
            groups={}
            for n in self.workflow.source_paths:groups.setdefault(self.expected[n],[]).append(n)
            missing={h:names for h,names in groups.items() if h not in produced}
            if missing:
                raise ToolError('merge delivery missing original SHA groups, including empty files when present: '
                                +json.dumps(missing,ensure_ascii=False)
                                +'; use actual hash_files groups and the actual representative rule; copy each missing group once before submitting.')
        receipt=super().submit_report(summary,current_ids(self),gaps,report_kind,search_receipt_id)
        return finish_report(self,receipt,file_ids,{'workflow_contract_version':VERSION,
                                                  'workflow_execution_version_sha256':workflow_version()})

def serve():
    scene=WorkflowScene(json.loads(Path(os.environ['FM_TASK_FILE']).read_text()),os.environ['FM_OUTPUT']);server=MCPServer('file_management')
    for name in TOOLS:
        server.tool(name=name,annotations=ToolAnnotations(readOnlyHint=name not in ('build_index','execute_plan','restore_plan','submit_report'),destructiveHint=False,openWorldHint=False))(getattr(scene,name))
    server.run()
if __name__=='__main__':serve()
